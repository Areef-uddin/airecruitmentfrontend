import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:go_router/go_router.dart';
import '../../core/theme/app_colors.dart';
import '../../core/theme/app_typography.dart';
import '../../core/responsive/responsive_layout.dart';
import '../../shared/widgets/top_navbar.dart';
import '../../shared/widgets/sidebar_navigation.dart';
import '../../shared/widgets/app_card.dart';
import '../../shared/widgets/app_button.dart';
import '../../shared/widgets/app_text_field.dart';
import '../../providers/auth_provider.dart';
import '../../repositories/ai_repository.dart';
import '../../repositories/job_repository.dart';

class RecruiterCreateJobScreen extends ConsumerStatefulWidget {
  const RecruiterCreateJobScreen({super.key});

  @override
  ConsumerState<RecruiterCreateJobScreen> createState() => _RecruiterCreateJobScreenState();
}

class _RecruiterCreateJobScreenState extends ConsumerState<RecruiterCreateJobScreen> {
  final _titleController = TextEditingController(text: 'Staff Machine Learning Engineer');
  final _locationController = TextEditingController(text: 'San Francisco, CA / Remote');
  final _minSalaryController = TextEditingController(text: '180000');
  final _maxSalaryController = TextEditingController(text: '225000');
  final _descController = TextEditingController();
  final _respController = TextEditingController();
  final _reqController = TextEditingController();
  final _benefitsController = TextEditingController();
  final _skillsController = TextEditingController(text: 'Python, PyTorch, Docker, Kubernetes, LLM Fine-tuning');

  String _workplaceType = 'REMOTE';
  String _jobType = 'FULL_TIME';
  String _experienceLevel = 'LEAD';

  bool _isGeneratingAI = false;
  bool _isPublishing = false;

  void _generateWithAI() async {
    setState(() => _isGeneratingAI = true);
    try {
      final aiRepo = AIRepository();
      final skillsList = _skillsController.text.split(',').map((s) => s.trim()).toList();

      final res = await aiRepo.generateJobDescription(
        title: _titleController.text.trim(),
        experienceLevel: _experienceLevel,
        workplaceType: _workplaceType,
        skills: skillsList,
      );

      setState(() {
        _descController.text = res['description'] ?? '';
        _respController.text = res['responsibilities'] ?? '';
        _reqController.text = res['requirements'] ?? '';
        _benefitsController.text = res['benefits'] ?? '';
        _isGeneratingAI = false;
      });

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('✨ Job description successfully generated by AI!')),
        );
      }
    } catch (_) {
      setState(() => _isGeneratingAI = false);
    }
  }

  void _publishJob() async {
    setState(() => _isPublishing = true);
    try {
      final repo = JobRepository();
      await repo.createJob({
        'title': _titleController.text.trim(),
        'description': _descController.text.trim().isNotEmpty
            ? _descController.text.trim()
            : 'Join our elite engineering organization to build next-generation platforms.',
        'responsibilities': _respController.text.trim(),
        'requirements': _reqController.text.trim(),
        'benefits': _benefitsController.text.trim(),
        'location': _locationController.text.trim(),
        'job_type': _jobType,
        'workplace_type': _workplaceType,
        'experience_level': _experienceLevel,
        'min_salary': double.tryParse(_minSalaryController.text) ?? 150000.0,
        'max_salary': double.tryParse(_maxSalaryController.text) ?? 200000.0,
        'skills_list': _skillsController.text.split(',').map((s) => s.trim()).toList(),
      });

      setState(() => _isPublishing = false);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Job posted successfully!')),
        );
        context.go('/recruiter/dashboard');
      }
    } catch (e) {
      setState(() => _isPublishing = false);
    }
  }

  Widget _buildWorkplaceDropdown() {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text('Workplace Model', style: AppTypography.labelLarge),
        const SizedBox(height: 8),
        DropdownButtonFormField<String>(
          value: _workplaceType,
          dropdownColor: AppColors.surfaceElevated,
          style: const TextStyle(color: Colors.white),
          decoration: InputDecoration(
            filled: true,
            fillColor: AppColors.surfaceLight,
            border: OutlineInputBorder(borderRadius: BorderRadius.circular(12), borderSide: const BorderSide(color: AppColors.border)),
          ),
          items: const [
            DropdownMenuItem(value: 'REMOTE', child: Text('Remote')),
            DropdownMenuItem(value: 'HYBRID', child: Text('Hybrid')),
            DropdownMenuItem(value: 'ONSITE', child: Text('On-site')),
          ],
          onChanged: (v) => setState(() => _workplaceType = v!),
        ),
      ],
    );
  }

  @override
  Widget build(BuildContext context) {
    final user = ref.watch(authProvider).user;
    final isDesktop = ResponsiveLayout.isDesktop(context);

    return Scaffold(
      backgroundColor: AppColors.background,
      body: Column(
        children: [
          const TopNavbar(),
          Expanded(
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                if (isDesktop)
                  SidebarNavigation(user: user, currentRoute: '/recruiter/create-job'),
                Expanded(
                  child: SingleChildScrollView(
                    padding: EdgeInsets.all(isDesktop ? 32 : 16),
                    child: Center(
                      child: ConstrainedBox(
                        constraints: const BoxConstraints(maxWidth: 880),
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            if (isDesktop)
                              Row(
                                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                children: [
                                  Column(
                                    crossAxisAlignment: CrossAxisAlignment.start,
                                    children: [
                                      Text('Post New Job Opening', style: AppTypography.displaySmall.copyWith(fontSize: 26)),
                                      const SizedBox(height: 4),
                                      Text('Use our AI Job Architect to automatically generate engaging specs.', style: AppTypography.bodySmall),
                                    ],
                                  ),
                                  AppButton(
                                    label: 'Auto-Draft with AI',
                                    icon: const Icon(Icons.auto_awesome, size: 16, color: Colors.white),
                                    isLoading: _isGeneratingAI,
                                    onPressed: _generateWithAI,
                                  ),
                                ],
                              )
                            else
                              Column(
                                crossAxisAlignment: CrossAxisAlignment.start,
                                children: [
                                  Text('Post New Job Opening', style: AppTypography.displaySmall.copyWith(fontSize: 22)),
                                  const SizedBox(height: 4),
                                  Text('Use our AI Job Architect to automatically generate engaging specs.', style: AppTypography.bodySmall),
                                  const SizedBox(height: 14),
                                  AppButton(
                                    label: 'Auto-Draft with AI',
                                    icon: const Icon(Icons.auto_awesome, size: 16, color: Colors.white),
                                    isLoading: _isGeneratingAI,
                                    onPressed: _generateWithAI,
                                  ),
                                ],
                              ),
                            const SizedBox(height: 24),

                            AppCard(
                              child: Column(
                                crossAxisAlignment: CrossAxisAlignment.start,
                                children: [
                                  AppTextField(
                                    label: 'Job Title',
                                    controller: _titleController,
                                  ),
                                  const SizedBox(height: 16),

                                  if (isDesktop)
                                    Row(
                                      children: [
                                        Expanded(
                                          child: AppTextField(
                                            label: 'Location',
                                            controller: _locationController,
                                          ),
                                        ),
                                        const SizedBox(width: 16),
                                        Expanded(child: _buildWorkplaceDropdown()),
                                      ],
                                    )
                                  else ...[
                                    AppTextField(
                                      label: 'Location',
                                      controller: _locationController,
                                    ),
                                    const SizedBox(height: 16),
                                    _buildWorkplaceDropdown(),
                                  ],
                                  const SizedBox(height: 16),

                                  if (isDesktop)
                                    Row(
                                      children: [
                                        Expanded(
                                          child: AppTextField(
                                            label: 'Min Salary (USD)',
                                            controller: _minSalaryController,
                                            keyboardType: TextInputType.number,
                                          ),
                                        ),
                                        const SizedBox(width: 16),
                                        Expanded(
                                          child: AppTextField(
                                            label: 'Max Salary (USD)',
                                            controller: _maxSalaryController,
                                            keyboardType: TextInputType.number,
                                          ),
                                        ),
                                      ],
                                    )
                                  else ...[
                                    AppTextField(
                                      label: 'Min Salary (USD)',
                                      controller: _minSalaryController,
                                      keyboardType: TextInputType.number,
                                    ),
                                    const SizedBox(height: 16),
                                    AppTextField(
                                      label: 'Max Salary (USD)',
                                      controller: _maxSalaryController,
                                      keyboardType: TextInputType.number,
                                    ),
                                  ],
                                  const SizedBox(height: 16),

                                  AppTextField(
                                    label: 'Target Skills (Comma Separated)',
                                    controller: _skillsController,
                                  ),
                                  const SizedBox(height: 20),

                                  const Divider(),
                                  const SizedBox(height: 16),

                                  AppTextField(
                                    label: 'Job Overview / Description',
                                    hint: 'Click "Auto-Draft with AI" above to generate with one click...',
                                    controller: _descController,
                                    maxLines: 4,
                                  ),
                                  const SizedBox(height: 16),

                                  AppTextField(
                                    label: 'Core Responsibilities',
                                    controller: _respController,
                                    maxLines: 4,
                                  ),
                                  const SizedBox(height: 16),

                                  AppTextField(
                                    label: 'Required Qualifications',
                                    controller: _reqController,
                                    maxLines: 4,
                                  ),
                                  const SizedBox(height: 16),

                                  AppTextField(
                                    label: 'Benefits & Perks',
                                    controller: _benefitsController,
                                    maxLines: 3,
                                  ),
                                  const SizedBox(height: 28),

                                  Align(
                                    alignment: isDesktop ? Alignment.centerRight : Alignment.center,
                                    child: AppButton(
                                      label: 'Publish Job to Board',
                                      isLoading: _isPublishing,
                                      onPressed: _publishJob,
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ],
                        ),
                      ),
                    ),
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}
